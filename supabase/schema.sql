create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id) values (new.id)
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.set_inventory_item_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_inventory on auth.users;
create trigger on_auth_user_created_inventory
after insert on auth.users
for each row execute function public.create_profile_for_new_user();

drop trigger if exists set_inventory_item_updated_at on public.inventory_items;
create trigger set_inventory_item_updated_at
before update on public.inventory_items
for each row execute function public.set_inventory_item_updated_at();

create or replace function public.is_inventory_host()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'HOST'
  );
$$;

create or replace function public.host_setup_required()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select not exists (select 1 from public.profiles where role = 'HOST');
$$;

create or replace function public.delete_all_inventory()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  deleted_count bigint;
begin
  if not public.is_inventory_host() then
    raise exception 'Akses hanya tersedia untuk akun HOST.';
  end if;

  delete from public.inventory_items;
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

create or replace function public.import_inventory(items jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  imported_count integer;
begin
  if not public.is_inventory_host() then
    raise exception 'Akses hanya tersedia untuk akun HOST.';
  end if;

  if items is null or jsonb_typeof(items) <> 'array' then
    raise exception 'Data impor harus berupa daftar material.';
  end if;

  if jsonb_array_length(items) < 1 or jsonb_array_length(items) > 10000 then
    raise exception 'Jumlah baris impor harus antara 1 dan 10.000.';
  end if;

  insert into public.inventory_items (
    ppm, material_description, part_category, sub_category,
    jan_26, feb_26, mar_26, apr_26, may_26, jun_26, jul_26, aug_26, sep_26,
    average_monthly_update, average, average_daily, lead_time_full, cycle_stock,
    service_factor, lead_time_factor, standard_deviation_update, safety_stock,
    lead_time, max_stock, status, price, max_value, stock_2026_10_20_update,
    rop_minstock, roq_order, qty_order, purchase_requisition, purchase_order,
    durasi_stock_bulan, durasi_roq_bulan, minimum_order_quantity
  )
  select
    btrim(row_data.ppm), coalesce(row_data.material_description, ''),
    coalesce(row_data.part_category, ''), coalesce(row_data.sub_category, ''),
    coalesce(row_data.jan_26, ''), coalesce(row_data.feb_26, ''),
    coalesce(row_data.mar_26, ''), coalesce(row_data.apr_26, ''),
    coalesce(row_data.may_26, ''), coalesce(row_data.jun_26, ''),
    coalesce(row_data.jul_26, ''), coalesce(row_data.aug_26, ''),
    coalesce(row_data.sep_26, ''), coalesce(row_data.average_monthly_update, ''),
    coalesce(row_data.average, ''), coalesce(row_data.average_daily, ''),
    coalesce(row_data.lead_time_full, ''), coalesce(row_data.cycle_stock, ''),
    coalesce(row_data.service_factor, ''), coalesce(row_data.lead_time_factor, ''),
    coalesce(row_data.standard_deviation_update, ''), coalesce(row_data.safety_stock, ''),
    coalesce(row_data.lead_time, ''), coalesce(row_data.max_stock, ''),
    coalesce(row_data.status, ''), coalesce(row_data.price, ''),
    coalesce(row_data.max_value, ''), coalesce(row_data.stock_2026_10_20_update, ''),
    coalesce(row_data.rop_minstock, ''), coalesce(row_data.roq_order, ''),
    coalesce(row_data.qty_order, ''), coalesce(row_data.purchase_requisition, ''),
    coalesce(row_data.purchase_order, ''), coalesce(row_data.durasi_stock_bulan, ''),
    coalesce(row_data.durasi_roq_bulan, ''), coalesce(row_data.minimum_order_quantity, '')
  from jsonb_to_recordset(items) as row_data (
    ppm text, material_description text, part_category text, sub_category text,
    jan_26 text, feb_26 text, mar_26 text, apr_26 text, may_26 text, jun_26 text,
    jul_26 text, aug_26 text, sep_26 text, average_monthly_update text, average text,
    average_daily text, lead_time_full text, cycle_stock text, service_factor text,
    lead_time_factor text, standard_deviation_update text, safety_stock text,
    lead_time text, max_stock text, status text, price text, max_value text,
    stock_2026_10_20_update text, rop_minstock text, roq_order text, qty_order text,
    purchase_requisition text, purchase_order text, durasi_stock_bulan text,
    durasi_roq_bulan text, minimum_order_quantity text
  )
  on conflict (ppm) do update set
    material_description = excluded.material_description,
    part_category = excluded.part_category,
    sub_category = excluded.sub_category,
    jan_26 = excluded.jan_26,
    feb_26 = excluded.feb_26,
    mar_26 = excluded.mar_26,
    apr_26 = excluded.apr_26,
    may_26 = excluded.may_26,
    jun_26 = excluded.jun_26,
    jul_26 = excluded.jul_26,
    aug_26 = excluded.aug_26,
    sep_26 = excluded.sep_26,
    average_monthly_update = excluded.average_monthly_update,
    average = excluded.average,
    average_daily = excluded.average_daily,
    lead_time_full = excluded.lead_time_full,
    cycle_stock = excluded.cycle_stock,
    service_factor = excluded.service_factor,
    lead_time_factor = excluded.lead_time_factor,
    standard_deviation_update = excluded.standard_deviation_update,
    safety_stock = excluded.safety_stock,
    lead_time = excluded.lead_time,
    max_stock = excluded.max_stock,
    status = excluded.status,
    price = excluded.price,
    max_value = excluded.max_value,
    stock_2026_10_20_update = excluded.stock_2026_10_20_update,
    rop_minstock = excluded.rop_minstock,
    roq_order = excluded.roq_order,
    qty_order = excluded.qty_order,
    purchase_requisition = excluded.purchase_requisition,
    purchase_order = excluded.purchase_order,
    durasi_stock_bulan = excluded.durasi_stock_bulan,
    durasi_roq_bulan = excluded.durasi_roq_bulan,
    minimum_order_quantity = excluded.minimum_order_quantity,
    updated_at = now();

  get diagnostics imported_count = row_count;
  return imported_count;
end;
$$;

alter table public.profiles enable row level security;
alter table public.inventory_items enable row level security;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
on public.profiles for select to authenticated
using (id = (select auth.uid()));

drop policy if exists "HOST can manage inventory" on public.inventory_items;
create policy "HOST can manage inventory"
on public.inventory_items for all to authenticated
using ((select public.is_inventory_host()))
with check ((select public.is_inventory_host()));

